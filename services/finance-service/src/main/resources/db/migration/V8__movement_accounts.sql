CREATE FUNCTION finance.movement_accounts(company uuid)
RETURNS TABLE (id uuid, name text, methods text[], display_order integer)
LANGUAGE sql STABLE STRICT AS $$
    -- Keep the UUID v3 generated by S2-350, including its version and variant bits.
    SELECT overlay(overlay(hash PLACING '3' FROM 13 FOR 1)
                   PLACING substr('89ab', (get_byte(decode(hash, 'hex'), 8) >> 4 & 3) + 1, 1)
                   FROM 17 FOR 1)::uuid,
           template.name, template.methods, template.display_order
    FROM finance.movement_account_templates template
    CROSS JOIN LATERAL (SELECT md5(company::text || ':finance:' || template.code) AS hash) digest
$$;

