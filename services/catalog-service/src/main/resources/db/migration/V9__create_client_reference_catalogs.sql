CREATE TABLE catalog.client_categories (
    id UUID PRIMARY KEY,
    company_id UUID NOT NULL,
    code VARCHAR(32) NOT NULL CHECK (code ~ '^[A-Z][A-Z0-9_]{0,31}$'),
    name VARCHAR(100) NOT NULL CHECK (btrim(name) <> ''),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    UNIQUE (company_id, id),
    UNIQUE (company_id, code),
    CHECK (code <> 'REGULAR' OR status = 'ACTIVE')
);

CREATE TABLE catalog.client_countries (
    code VARCHAR(2) PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE catalog.client_provinces (
    country_code VARCHAR(2) NOT NULL REFERENCES catalog.client_countries,
    code VARCHAR(8) NOT NULL,
    name TEXT NOT NULL,
    PRIMARY KEY (country_code, code)
);

CREATE TABLE catalog.client_municipalities (
    country_code VARCHAR(2) NOT NULL,
    province_code VARCHAR(8) NOT NULL,
    code VARCHAR(8) NOT NULL,
    name TEXT NOT NULL,
    PRIMARY KEY (country_code, province_code, code),
    FOREIGN KEY (country_code, province_code) REFERENCES catalog.client_provinces
);

CREATE TABLE catalog.client_receipt_types (
    code VARCHAR(32) PRIMARY KEY,
    name TEXT NOT NULL,
    version TEXT NOT NULL,
    active BOOLEAN NOT NULL
);

